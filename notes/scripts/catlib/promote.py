RUN_ARGS: dict[str, Callable[[], tuple[str, ...]]] = {
    # The workflow page renders the ready-queue length, read through a subprocess the `open`
    # audit event never sees and no tree digest covers, so a bead close invalidates the record the
    # way a file change does. The fork head is not read: the page records it as a dated literal,
    # because the commit that lands a measured head moves the head the next measurement names.
    "render_reports.py": lambda: (str(bd_ready_count()),)
}


def git_short(ref: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", ref],
                          check=True, capture_output=True).stdout.decode("utf-8").strip()


def bd_ready_count() -> int:
    """The ready-queue length, read from the tally line bd prints for itself."""
    out = subprocess.run(["bd", "ready"], check=True, capture_output=True).stdout.decode("utf-8")
    return int(first_group(r"Ready: (\d+) issues", out) or 0)


def key_for(name: str, args: tuple[str, ...] = ()) -> str:
    """The builder's cache key: tree digests, the builder's source, its L1 inputs, its args."""
    script = SCRIPTS / name
    if name in L1_HEAD:
        texts = tuple(subprocess.run(["git", "-C", str(ROOT), "show", f"HEAD:{p.relative_to(ROOT)}"],
                                     check=True, capture_output=True).stdout.decode("utf-8")
                      for p in l1_paths(name))
    else:
        texts = tuple(p.read_text(encoding="utf-8") for p in l1_paths(name))
    fn = RUN_ARGS.get(name)
    extra = () if fn is None else fn()
    return digest_key(script.read_text(encoding="utf-8"), texts, tuple(args) + extra)


def checker_key(name: str, args: tuple[str, ...] = ()) -> str:
    """The checker row's cache key: tree digests, the checker's source, its CHECKER_L1 inputs, its args.

    Mirrors `measure_checker_reads.py`'s `RC.key(src, l1_texts, args)` formula so the gate and
    the probe compute the same key for the same row. Tree entries are expanded via `expand()`
    so a directory entry names the tracked files it contains.
    """
    src = (SCRIPTS / name).read_text(encoding="utf-8")
    paths = [pp for e in CHECKER_L1[name] for pp in expand(e)]
    texts = tuple(pp.read_text(encoding="utf-8", errors="replace") for pp in paths)
    return digest_key(src, texts, args)


def test_row_key(test_path: str, checker: str, args: tuple[str, ...] = ()) -> str:
    """The test row's cache key: test file + checker source + conftest.py + checker's L1.

    A test row's mutants target page content, so a page change can flip a test
    result. The key must name all four inputs that determine the test's outcome.
    """
    test_src = (ROOT / test_path).read_text(encoding="utf-8")
    checker_src = (SCRIPTS / checker).read_text(encoding="utf-8")
    conftest_src = (SCRIPTS / "tests" / "conftest.py").read_text(encoding="utf-8")
    paths = [pp for e in CHECKER_L1[checker] for pp in expand(e)]
    l1_texts = tuple(pp.read_text(encoding="utf-8", errors="replace") for pp in paths)
    return digest_key(test_src + "\n" + checker_src + "\n" + conftest_src, l1_texts, args)


def row_key(spec: str) -> tuple[str, list[str]] | None:
    """The keyable gate row's (cache_key, surface), or None for a non-keyable row.

    A checker row keys on its CHECKER_L1 surface. A test row keys on the test file,
    the checker source, conftest.py, and the checker's L1. The gate and the TSV
    writer (`measure_gate_rows.py`) both use this, so the two producers agree on
    which rows are keyable and on the surface each carries.
    """
    a = spec.split()
    name = a[0]
    if name in CHECKER_L1:
        return checker_key(name), list(CHECKER_L1[name])
    if name == "run_tests.py" and len(a) >= 2:
        test_path = a[1]
        base = test_path.rsplit("/", 1)[-1]
        if base.startswith("test_") and base.endswith(".py"):
            checker = "verify_" + base[len("test_"):]
            if checker in CHECKER_L1:
                args = tuple(a[2:])
                surface = sorted({
                    test_path, f"notes/scripts/{checker}", "notes/scripts/tests/conftest.py",
                    *CHECKER_L1[checker]
                })
                return test_row_key(test_path, checker, args), surface
    return None


def artifact_of(path: Path) -> str:
    """The cache artifact name: the repo-relative path, so pages in sibling dirs never collide."""
    return str(path.relative_to(ROOT))


def promote(path: Path, key: str, text: str) -> None:
    """The approval: cache the bytes under the key, then write the same bytes onto the tracked path."""
    cache_text(key, artifact_of(path), text)
    write_atomic(path, text)


def cached_text(path: Path, key: str) -> str | None:
    """The cached bytes for a tracked path under this key, or None when the cache has no entry."""
    p = RECORDS_ROOT / key / artifact_of(path)
    return p.read_text(encoding="utf-8") if p.is_file() else None


def prune_stale() -> int:
    """Delete key dirs under RECORDS_ROOT that no current producer owns.

    The key is a function of HEAD tree digests, so every commit orphans the
    previous key dir. This derives the current key set from the registry
    (ARTIFACTS | NON_CACHED via key_for, deterministic) and removes any key
    dir not in the set. The store is untracked (.qwen/*), so the removal is
    safe. Returns the number of dirs removed.
    """
    if not RECORDS_ROOT.is_dir():
        return 0
    current = set()
    for w in sorted(set(ARTIFACTS) | NON_CACHED):
        with contextlib.suppress(Exception):
            current.add(key_for(w, ARGS.get(w, ())))
    # The gate lands each keyable checker's record under its own key (math-eij.4), and the gate is
    # the producer: a writer row that prunes must not rmtree a key the gate owns.
    for c in sorted(CHECKER_L1):
        with contextlib.suppress(Exception):
            current.add(checker_key(c))
    removed = 0
    for d in sorted(RECORDS_ROOT.iterdir()):
        if d.is_dir() and d.name not in current:
            try:
                shutil.rmtree(d)
                removed += 1
            except OSError:
                # A concurrent row is removing the same key dir (the gate runs 12
                # rows in parallel, and several call prune_stale). The store is
                # untracked (.qwen/*), so a stale directory is harmless — the
                # next call removes it.
                pass
    return removed
